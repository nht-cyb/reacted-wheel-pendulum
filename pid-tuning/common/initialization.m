% This function initialize the first population of search agents.
% Shared by GWO (initial wolf pack) and ACO (initial solution archive).
%
%   SearchAgents_no : number of candidate solutions (rows)
%   dim             : number of decision variables (columns), here 6 PID gains
%   ub, lb          : upper / lower bounds, scalar or 1-by-dim vector
%   Positions       : SearchAgents_no-by-dim matrix, uniformly random in [lb, ub]
function Positions=initialization(SearchAgents_no,dim,ub,lb)

Boundary_no= size(ub,2); % numnber of boundaries

% If the boundaries of all variables are equal and user enter a signle
% number for both ub and lb
if Boundary_no==1
    Positions=rand(SearchAgents_no,dim).*(ub-lb)+lb;
end

% If each variable has a different lb and ub
if Boundary_no>1
    for i=1:dim
        ub_i=ub(i);
        lb_i=lb(i);
        Positions(:,i)=rand(SearchAgents_no,1).*(ub_i-lb_i)+lb_i;
    end
end
